function mergeKeys(en, newKeys) {
  for (const [section, keys] of Object.entries(newKeys)) {
    en[section] = { ...(en[section] || {}), ...keys };
  }
}

function walkVueFiles(dir, files = []) {
  for (const entry of fs.readdirSync(dir, { withFileTypes: true })) {
    const full = path.join(dir, entry.name);
    if (entry.isDirectory()) walkVueFiles(full, files);
    else if (entry.name.endsWith('.vue')) files.push(full);
  }
  return files;
}

function ensureUseI18n(content) {
  if (content.includes('useI18n')) return content;
  if (!content.includes("t('") && !content.includes('t("')) return content;

  if (content.includes('<script setup')) {
    return content.replace(
      /<script setup([^>]*)>/,
      "<script setup$1>\nimport { useI18n } from 'vue-i18n';\nconst { t } = useI18n();"
    );
  }
  return content;
}

function applyReplacements(content, replacements) {
  let out = content;
  let count = 0;
  for (const [from, to] of replacements) {
    if (out.includes(from)) {
      const parts = out.split(from);
      count += parts.length - 1;
      out = parts.join(to);
    }
  }
  return { content: out, count };
}

